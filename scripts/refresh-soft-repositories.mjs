import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GITHUB_OWNER = "ksukie";
const GITHUB_API_VERSION = "2022-11-28";
const checkOnly = process.argv.includes("--check");
const token = process.env.PORTFOLIO_REPOSITORIES_TOKEN;

if (!checkOnly && !token) {
  throw new Error("PORTFOLIO_REPOSITORIES_TOKEN is required to refresh Soft repository data.");
}

const headers = {
  Accept: "application/vnd.github+json",
  Authorization: `Bearer ${token}`,
  "X-GitHub-Api-Version": GITHUB_API_VERSION
};

async function fetchJson(url) {
  const response = await fetch(url, { headers });

  if (!response.ok) {
    throw new Error(`GitHub API request failed (${response.status}) for ${url}`);
  }

  return response.json();
}

function repositoryMetadata(repo) {
  return {
    name: repo.name,
    full_name: repo.full_name,
    private: Boolean(repo.private),
    visibility: repo.visibility || (repo.private ? "private" : "public"),
    description: repo.description ?? null,
    language: repo.language ?? null,
    topics: Array.isArray(repo.topics) ? repo.topics : [],
    homepage: repo.homepage ?? null,
    html_url: repo.html_url,
    stargazers_count: Number(repo.stargazers_count) || 0,
    forks_count: Number(repo.forks_count) || 0,
    pushed_at: repo.pushed_at ?? null,
    updated_at: repo.updated_at ?? null
  };
}

async function fetchOwnedRepositories() {
  const repositories = [];

  for (let page = 1; page <= 10; page += 1) {
    const url = new URL("https://api.github.com/user/repos");
    url.search = new URLSearchParams({
      affiliation: "owner",
      direction: "desc",
      page: String(page),
      per_page: "100",
      sort: "updated",
      visibility: "all"
    }).toString();

    const batch = await fetchJson(url);
    repositories.push(...batch);
    if (batch.length < 100) break;
  }

  return repositories.map(repositoryMetadata);
}

if (checkOnly) {
  const fixture = repositoryMetadata({
    name: "private-check",
    full_name: "ksukie/private-check",
    private: true,
    topics: ["portfolio"],
    stargazers_count: 2
  });
  assert.equal(fixture.visibility, "private");
  assert.deepEqual(fixture.topics, ["portfolio"]);
  assert.equal(fixture.stargazers_count, 2);
  console.log("Soft repository metadata check passed.");
} else {
  const authenticatedUser = await fetchJson("https://api.github.com/user");
  if (String(authenticatedUser.login || "").toLowerCase() !== GITHUB_OWNER) {
    throw new Error(`PORTFOLIO_REPOSITORIES_TOKEN must belong to ${GITHUB_OWNER}.`);
  }

  const repositories = await fetchOwnedRepositories();
  const privateRepositoryCount = repositories.filter((repo) => repo.private).length;
  const scriptDirectory = dirname(fileURLToPath(import.meta.url));
  const outputPath = resolve(scriptDirectory, "../js/soft-repositories.js");
  const source = [
    "// Generated by scripts/refresh-soft-repositories.mjs.",
    "// Repository metadata in this public file is intentionally visible on the portfolio.",
    `globalThis.REPOSITORY_SNAPSHOT = ${JSON.stringify(repositories, null, 2)};`,
    ""
  ].join("\n");

  await writeFile(outputPath, source, "utf8");
  console.log(`Refreshed ${repositories.length} repositories (${privateRepositoryCount} private).`);
}
